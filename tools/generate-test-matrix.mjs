#!/usr/bin/env node
// Renders docs/test-matrix.md from REAL Jest results, so a cell can only say EXECUTED if the test ran and passed.
//   npx jest --json --outputFile=<results.json> && node tools/generate-test-matrix.mjs <results.json>
// DB-backed suites (test/db) are skipped unless MONGODB_TEST_URI is set; skipped tests are reported as NOT EXECUTED.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const resultsPath = process.argv[2];
if (!resultsPath) throw new Error('usage: generate-test-matrix.mjs <jest-results.json>');
const results = JSON.parse(readFileSync(resultsPath, 'utf8'));
const spec = JSON.parse(readFileSync(join(root, 'docs/openapi.json'), 'utf8'));
const original = JSON.parse(readFileSync(join(root, 'docs/original-endpoints.json'), 'utf8'));

const tests = results.testResults.flatMap((f) =>
  f.assertionResults.map((a) => ({
    file: relative(root, f.name),
    title: a.fullName ?? a.title,
    status: a.status, // passed | failed | pending | todo
  })),
);
const byTitle = new Map(
  tests.map((t) => [t.title.replace(/^route matrix[^|]*?MATRIX/, 'MATRIX'), t]),
);
const find = (c, op) => {
  for (const [title, t] of byTitle) if (title.includes(`MATRIX|${c}|${op}`)) return t;
  return null;
};
const cell = (c, op, applicable) => {
  if (!applicable) return 'n/a';
  const t = find(c, op);
  if (!t) return 'WRITTEN, NOT EXECUTED';
  return (
    { passed: 'EXECUTED', failed: 'FAILED', pending: 'NOT EXECUTED (skipped)', todo: 'PLANNED' }[
      t.status
    ] ?? t.status
  );
};

const operations = Object.entries(spec.paths).flatMap(([path, item]) =>
  Object.entries(item).map(([m, op]) => ({
    key: `${m.toUpperCase()} ${path}`,
    method: m.toUpperCase(),
    path,
    access: op['x-access'],
    params: op.parameters ?? [],
    hasBody: op.requestBody !== undefined,
  })),
);

// Which feature spec files exercise a route? A literal-prefix search of the test sources (an index, not a proof).
const specFiles = [];
const walk = (dir) => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.spec.ts')) specFiles.push(p);
  }
};
walk(join(root, 'test'));
const sources = specFiles.map((f) => ({ file: relative(root, f), text: readFileSync(f, 'utf8') }));
const fileState = (file) => {
  const own = tests.filter((t) => t.file === file);
  if (own.length === 0) return 'WRITTEN, NOT EXECUTED';
  if (own.some((t) => t.status === 'failed')) return 'FAILED';
  if (own.every((t) => t.status === 'pending')) return 'NOT EXECUTED (skipped)';
  return own.some((t) => t.status === 'pending') ? 'EXECUTED (partly skipped)' : 'EXECUTED';
};
const referencing = (op) => {
  const literal = op.path.split('{')[0].replace(/\/$/, '');
  return sources
    .filter(
      (s) =>
        !s.file.endsWith('matrix.spec.ts') &&
        !s.file.endsWith('openapi.spec.ts') &&
        s.text.includes(literal),
    )
    .map((s) => s.file.replace(/^test\//, ''));
};

const out = [];
const w = (s = '') => out.push(s);
const total = tests.length;
const count = (s) => tests.filter((t) => t.status === s).length;
w('# Test matrix');
w();
w(
  '> Generated by `tools/generate-test-matrix.mjs` from real Jest output. **Do not edit by hand.**',
);
w(
  '> A cell says `EXECUTED` only if that exact test ran and passed in the run this file was generated from.',
);
w();
w('## Run summary');
w();
w(
  `| Result | Count |\n|---|---|\n| Passed (EXECUTED) | ${count('passed')} |\n| Failed | ${count('failed')} |\n| Skipped (NOT EXECUTED) | ${count('pending')} |\n| Total | ${total} |`,
);
w();
const dbTests = tests.filter((t) => t.file.startsWith('test/db/'));
const dbRan = dbTests.filter((t) => t.status === 'passed' || t.status === 'failed').length;
w(
  dbRan === 0
    ? `**MongoDB integration: NOT EXECUTED.** ${dbTests.length} tests in \`test/db\` were skipped because no real MongoDB was configured for this run (\`MONGODB_TEST_URI\` unset). Everything below that says EXECUTED ran against in-memory fakes, not MongoDB.`
    : `**MongoDB integration:** ${dbRan} of ${dbTests.length} tests in \`test/db\` ran against a real MongoDB (passed: ${dbTests.filter((t) => t.status === 'passed').length}, failed: ${dbTests.filter((t) => t.status === 'failed').length}).`,
);
w();
w('## Per-suite results');
w();
w('| Suite | Passed | Failed | Skipped |\n|---|---|---|---|');
for (const f of [...new Set(tests.map((t) => t.file))].sort()) {
  const own = tests.filter((t) => t.file === f);
  const n = (s) => own.filter((t) => t.status === s).length;
  w(`| \`${f}\` | ${n('passed')} | ${n('failed')} | ${n('pending')} |`);
}
w();

w('## A. Every endpoint of the original `nestapp` (35)');
w();
w('| # | Original endpoint | What happened | Now served by | Evidence |\n|---|---|---|---|---|');
for (const e of original) {
  const now = e.now ? `\`${e.now.replace('{', '{').replace(/^(\w+) \/(?!api)/, '$1 /')}\`` : '—';
  let evidence;
  if (e.now) {
    const op = operations.find((o) => o.key === e.now);
    evidence = op
      ? `matrix row below (${referencing(op).length} feature suite(s))`
      : '**MISSING FROM SPEC**';
  } else if (e.probe) {
    const t = find('removed-404', e.original);
    evidence = `removed-route probe: ${t ? (t.status === 'passed' ? 'EXECUTED' : t.status.toUpperCase()) : 'WRITTEN, NOT EXECUTED'}`;
  } else {
    evidence = `dependency-absence check: ${find('removed-dependency', 'no file-upload')?.status === 'passed' ? 'EXECUTED' : 'NOT EXECUTED'}`;
  }
  w(
    `| ${e.n} | \`${e.original}\` | ${e.fate}${e.note ? ` (${e.note})` : ''} | ${now} | ${evidence} |`,
  );
}
w();

w(`## B. Every endpoint of this API (${operations.length}) × cross-cutting checks`);
w();
w(
  'Cells come from `test/matrix.spec.ts`, which builds its cases from the generated OpenAPI file. `n/a` = the check does not apply to that route.',
);
w();
const cols = [
  ['no-token-401', 'No token → 401', (o) => !o.access.startsWith('public')],
  ['bad-token-401', 'Bad token → 401', (o) => !o.access.startsWith('public')],
  ['customer-403', 'Customer → 403', (o) => o.access === 'ADMIN'],
  ['viewer-403', 'Demo viewer → 403', (o) => o.access === 'ADMIN'],
  [
    'demo-write-403',
    'Demo write → 403',
    (o) => !o.access.startsWith('public') && o.method !== 'GET',
  ],
  ['bad-id-400', 'Bad id → 400', (o) => o.params.some((p) => p.in === 'path')],
  ['unknown-field-400', 'Unknown field → 400', (o) => o.hasBody],
  ['bad-json-400', 'Malformed JSON → 400', (o) => o.hasBody],
  [
    'bad-query-400',
    'Bad limit → 400',
    (o) => o.params.some((p) => p.in === 'query' && p.name === 'limit'),
  ],
];
w(`| Endpoint | Access | ${cols.map((c) => c[1]).join(' | ')} | Feature suites |`);
w(`|---|---|${cols.map(() => '---').join('|')}|---|`);
for (const op of operations) {
  const cells = cols.map(([id, , applies]) => cell(id, op.key, applies(op)));
  const suites = referencing(op)
    .map((f) => `${f} (${fileState('test/' + f)})`)
    .join('<br>');
  w(`| \`${op.key}\` | ${op.access} | ${cells.join(' | ')} | ${suites || 'none (matrix only)'} |`);
}
w();
w('## C. Not covered by this matrix');
w();
w(
  '- Business rules (stock, coupons, order state machine, masking, audit) are covered by the feature suites, not by these generic probes.',
);
w('- The browser UI is covered by the separate frontend suite (`web/`), not listed here.');
w('- No load, penetration or real-payment testing was done; payments are simulated by design.');
w();
writeFileSync(join(root, 'docs/test-matrix.md'), out.join('\n'));
console.log(`wrote docs/test-matrix.md (${operations.length} operations, ${total} tests)`);
