#!/usr/bin/env node
// Renders docs/coverage-report.md from the coverage summary Jest produced (npm run test:cov).
// Phase-1 targets: >=85% statements and >=75% branches on services, guards and pipes. Gaps are listed, not hidden.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const summary = JSON.parse(readFileSync(join(root, 'coverage/coverage-summary.json'), 'utf8'));
const files = Object.entries(summary)
  .filter(([k]) => k !== 'total')
  .map(([k, v]) => ({ file: relative(root, k), ...v }));

const TARGET = { statements: 85, branches: 75 };
const pct = (c, t) => (t === 0 ? 100 : (c / t) * 100);
const sum = (list, key) => ({
  covered: list.reduce((n, f) => n + f[key].covered, 0),
  total: list.reduce((n, f) => n + f[key].total, 0),
});
const row = (label, list) => {
  const cells = ['statements', 'branches', 'functions', 'lines'].map((k) => {
    const s = sum(list, k);
    return `${pct(s.covered, s.total).toFixed(2)}% (${s.covered}/${s.total})`;
  });
  return `| ${label} | ${list.length} | ${cells.join(' | ')} |`;
};
// auth/dto.ts and catalogue/dto.ts hold the Zod validation pipes (ZodPipe / ZodBodyPipe), so they are in scope.
const isKey = (f) =>
  /\.(service|guards?|pipe|pipes)\.ts$/.test(f.file) ||
  /\/(guards|pipes)\.ts$/.test(f.file) ||
  /\/(auth|catalogue)\/dto\.ts$/.test(f.file);
const key = files.filter(isKey);
const keyS = pct(sum(key, 'statements').covered, sum(key, 'statements').total);
const keyB = pct(sum(key, 'branches').covered, sum(key, 'branches').total);
const verdict = (v, t) => (v >= t ? 'MET' : 'NOT MET');

const out = [];
out.push('# Coverage report', '');
out.push(
  '> Generated by `tools/generate-coverage-report.mjs` from `npm run test:cov` (in-memory fakes only; the 42 MongoDB tests are skipped unless a real MongoDB is configured, so **Mongoose repository code is largely unmeasured here**). Do not edit by hand.',
  '',
);
out.push(
  '| Scope | Files | Statements | Branches | Functions | Lines |',
  '|---|---|---|---|---|---|',
);
out.push(row('All of `src/` (excluding `main.ts`, `openapi/generate.ts`)', files));
out.push(row('Services, guards and pipes (target scope)', key));
out.push('', '## Phase-1 targets', '');
out.push('| Target | Required | Actual | Result |', '|---|---|---|---|');
out.push(
  `| Statements, services/guards/pipes | ≥ ${TARGET.statements}% | ${keyS.toFixed(2)}% | **${verdict(keyS, TARGET.statements)}** |`,
);
out.push(
  `| Branches, services/guards/pipes | ≥ ${TARGET.branches}% | ${keyB.toFixed(2)}% | **${verdict(keyB, TARGET.branches)}** |`,
);
out.push('', '## Target-scope files, lowest branch coverage first', '');
out.push('| File | Statements | Branches |', '|---|---|---|');
for (const f of [...key].sort((a, b) => a.branches.pct - b.branches.pct)) {
  out.push(`| \`${f.file}\` | ${f.statements.pct}% | ${f.branches.pct}% |`);
}
out.push('', '## Least-covered files in all of `src/`', '');
out.push('| File | Statements | Branches |', '|---|---|---|');
for (const f of [...files].sort((a, b) => a.statements.pct - b.statements.pct).slice(0, 10)) {
  out.push(`| \`${f.file}\` | ${f.statements.pct}% | ${f.branches.pct}% |`);
}
out.push('', '## How to read this', '');
out.push(
  '- Mongoose repositories (`mongo-*.repository.ts`) are exercised only by `test/db`, which needs a real MongoDB; low numbers there are expected until those tests are run.',
);
out.push('- Percentages measure executed code, not correctness.');
writeFileSync(join(root, 'docs/coverage-report.md'), out.join('\n') + '\n');
console.log(`target scope: statements ${keyS.toFixed(2)}% branches ${keyB.toFixed(2)}%`);
